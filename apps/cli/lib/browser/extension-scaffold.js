import fs from 'fs/promises';
import path from 'path';
import chalk from 'chalk';
import { printSuccess, printInfo } from '../utils/output.js';

export async function scaffoldChromeExtension(targetDir = '.') {
  const root = path.resolve(targetDir);

  // Ensure directory exists
  await fs.mkdir(root, { recursive: true });

  // Manifest V3
  const manifest = {
    manifest_version: 3,
    name: 'Ultra-Dex Generated Extension',
    version: '1.0.0',
    description: 'A Chrome extension generated by Ultra-Dex',
    permissions: ['activeTab', 'storage'],
    action: {
      default_popup: 'popup.html',
      default_icon: 'icon.png',
    },
    background: {
      service_worker: 'background.js',
    },
    content_scripts: [
      {
        matches: ['<all_urls>'],
        js: ['content.js'],
      },
    ],
  };

  // Background Script
  const backgroundJs = `// Ultra-Dex Generated Background Script
chrome.runtime.onInstalled.addListener(() => {
  console.log('Extension installed');
});
`;

  // Content Script
  const contentJs = `// Ultra-Dex Generated Content Script
console.log('Ultra-Dex content script loaded');
`;

  // Popup HTML
  const popupHtml = `<!DOCTYPE html>
<html>
<head>
  <style>
    body { width: 300px; padding: 10px; font-family: sans-serif; }
    h1 { font-size: 16px; }
  </style>
</head>
<body>
  <h1>Ultra-Dex Extension</h1>
  <p>Generated successfully.</p>
  <script src="popup.js"></script>
</body>
</html>`;

  // Popup JS
  const popupJs = `console.log('Popup script loaded');`;

  // Write files
  await fs.writeFile(path.join(root, 'manifest.json'), JSON.stringify(manifest, null, 2));
  await fs.writeFile(path.join(root, 'background.js'), backgroundJs);
  await fs.writeFile(path.join(root, 'content.js'), contentJs);
  await fs.writeFile(path.join(root, 'popup.html'), popupHtml);
  await fs.writeFile(path.join(root, 'popup.js'), popupJs);

  // Create empty icon
  await fs.writeFile(path.join(root, 'icon.png'), '');

  printSuccess(
    chalk.green(`
✅ Chrome Extension scaffolded in ${root}`)
  );
  printInfo(chalk.gray('Files created:'));
  printInfo(chalk.gray('  - manifest.json'));
  printInfo(chalk.gray('  - background.js'));
  printInfo(chalk.gray('  - content.js'));
  printInfo(chalk.gray('  - popup.html'));
}

/**
 * Safe execution wrapper with error handling for extension-scaffold
 * @param {Function} fn - Async function to execute
 * @param {string} [context='extension-scaffold'] - Error context
 * @returns {Promise<*>} Result or null on error
 */
async function _safeExecute(fn, context = 'extension-scaffold') {
  try {
    return await fn();
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`[${context}] Error: ${message}`);
    return null;
  }
}
