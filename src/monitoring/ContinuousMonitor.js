  async getOptimizationRecommendations() {
    // Get optimization recommendations based on cycle history
    const recentCycles = this.cycleHistory.slice(-10); // Last 10 cycles
    
    if (recentCycles.length === 0) {
      return {
        immediate: [],
        shortTerm: [],
        longTerm: []
      };
    }
    
    // Analyze patterns in recent cycles
    const patterns = this.analyzeOptimizationPatterns(recentCycles);
    
    return {
      immediate: patterns.frequentIssues.map(issue => ({
        issue,
        priority: 'high',
        recommendation: `address_${issue.type.replace(/\s+/g, '_')}_immediately`,
        impact: 'high_immediate_benefit'
      })),
      shortTerm: patterns.commonOpportunities.map(opp => ({
        opportunity: opp,
        priority: 'medium',
        recommendation: `implement_${opp.type.replace(/\s+/g, '_')}_optimization`,
        impact: 'medium_term_benefit',
        timeline: '2-4_weeks'
      })),
      longTerm: patterns.systemicIssues.map(issue => ({
        issue,
        priority: 'medium',
        recommendation: `address_${issue.type.replace(/\s+/g, '_')}_systemically`,
        impact: 'long_term_architectural_benefit',
        timeline: '3-6_months'
      }))
    };
  }

  analyzeOptimizationPatterns(cycles) {
    // Analyze patterns in optimization cycles
    const issueFrequency = {};
    const opportunityFrequency = {};
    const systemicIssues = [];
    
    for (const cycle of cycles) {
      for (const issue of cycle.analysis.performanceIssues) {
        issueFrequency[issue.type] = (issueFrequency[issue.type] || 0) + 1;
      }
      
      for (const opp of cycle.opportunities) {
        opportunityFrequency[opp.type] = (opportunityFrequency[opp.type] || 0) + 1;
      }
    }
    
    // Identify frequent issues (appearing in >70% of cycles)
    const frequentIssues = Object.entries(issueFrequency)
      .filter(([type, count]) => count / cycles.length > 0.7)
      .map(([type, count]) => ({ type, frequency: count / cycles.length }));
    
    // Identify common opportunities (appearing in >50% of cycles)
    const commonOpportunities = Object.entries(opportunityFrequency)
      .filter(([type, count]) => count / cycles.length > 0.5)
      .map(([type, count]) => ({ type, frequency: count / cycles.length }));
    
    // Identify systemic issues that require architectural changes
    if (frequentIssues.some(issue => issue.type.includes('scalability'))) {
      systemicIssues.push({
        type: 'architectural_scaling',
        description: 'System requires fundamental architectural changes for scaling'
      });
    }
    
    if (frequentIssues.some(issue => issue.type.includes('performance'))) {
      systemicIssues.push({
        type: 'performance_architecture',
        description: 'Performance requires architectural improvements'
      });
    }
    
    return {
      frequentIssues,
      commonOpportunities,
      systemicIssues
    };
  }

